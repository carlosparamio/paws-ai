# frozen_string_literal: true

module PAWS
  module Graphics
    # PAW stores shade operations as two 4-bit pattern ids packed into one byte.
    # Extracted snapshots provide the 16-entry pattern table from charset set 0;
    # the built-in table remains only as a fallback for older JSON fixtures or
    # hand-authored games that do not declare shade patterns.
    class ShadePattern
      # PAW's family-2 shade routine indexes this 16-entry table with each
      # nibble of the shade byte. Each entry is an 8-row bitmap mask.
      NIBBLE_PATTERNS = {
        0x0 => [0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55],
        0x1 => [0xCC, 0x33, 0xCC, 0x33, 0xCC, 0x33, 0xCC, 0x33],
        0x2 => [0xAA, 0xAA, 0x55, 0x55, 0xAA, 0xAA, 0x55, 0x55],
        0x3 => [0x88, 0x00, 0x02, 0x00, 0x88, 0x00, 0x20, 0x00],
        0x4 => [0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x02, 0x00],
        0x5 => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10],
        0x6 => [0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0x00],
        0x7 => [0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44],
        0x8 => [0x00, 0xFF, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x00],
        0x9 => [0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01],
        0xA => [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80],
        0xB => [0x22, 0x11, 0x88, 0x44, 0x22, 0x11, 0x88, 0x44],
        0xC => [0x44, 0x88, 0x11, 0x22, 0x44, 0x88, 0x11, 0x22],
        0xD => [0xC3, 0x3C, 0xC3, 0x3C, 0xC3, 0x3C, 0xC3, 0x3C],
        0xE => [0x04, 0x04, 0xFF, 0x40, 0x40, 0x40, 0xFF, 0x04],
        0xF => [0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF],
      }.freeze

      def self.pixel?(pattern_byte, x, y, patterns: nil, inverse: false)
        return false unless pattern_byte

        first = (pattern_byte >> 4) & 0x0F
        second = pattern_byte & 0x0F
        mask = 0x80 >> (x % 8)
        row = y % 8
        pixel = (pattern_for(first, patterns).fetch(row) & mask) != 0 ||
          (pattern_for(second, patterns).fetch(row) & mask) != 0
        inverse ? !pixel : pixel
      end

      def self.pattern_for(pattern_id, patterns)
        return patterns.fetch(pattern_id) if patterns&.key?(pattern_id)

        NIBBLE_PATTERNS.fetch(pattern_id)
      end
    end
  end
end
